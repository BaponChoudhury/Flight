// Regenerates supabase/migrations/0002_seed.sql from src/lib/config/defaults.ts.
// Run: npx tsx scripts/gen-seed.ts
import { writeFileSync } from "node:fs";
import { defaultConfig } from "../src/lib/config/defaults";

const lit = (v: unknown): string =>
  v === null || v === undefined
    ? "null"
    : typeof v === "number" || typeof v === "boolean"
      ? String(v)
      : `'${String(v).replace(/'/g, "''")}'`;

function insert(table: string, rows: Record<string, unknown>[]): string {
  if (!rows.length) return "";
  const cols = Object.keys(rows[0]);
  const values = rows.map((r) => `  (${cols.map((c) => lit(r[c])).join(", ")})`).join(",\n");
  return `insert into ${table} (${cols.join(", ")}) values\n${values}\non conflict do nothing;\n\n`;
}

const c = defaultConfig();
let sql = "-- Seed data (generated by scripts/gen-seed.ts). Safe to re-run: existing rows are kept.\n\n";
sql += insert("airports", c.airports as never);
sql += insert("ground_access", c.groundAccess as never);
sql += insert("bag_fees", c.bagFees as never);
sql += insert("airline_bag_defaults", c.airlineBagDefaults as never);
sql += insert("airline_terminals", c.airlineTerminals as never);
sql += insert("terminal_rules", c.terminalRules as never);
const settingsRows = Object.entries(c.settings).map(([key, value]) => `  (${lit(key)}, ${lit(JSON.stringify(value))}::jsonb)`);
sql += `insert into settings (key, value) values\n${settingsRows.join(",\n")}\non conflict do nothing;\n`;

writeFileSync("supabase/migrations/0002_seed.sql", sql);
console.log("wrote supabase/migrations/0002_seed.sql");
